def slugify(name: str) -> str:
    cleaned = name.lower()
    cleaned = cleaned.replace("’", "").replace("'", "").replace("‘", "").replace("`", "")
    cleaned = re.sub(r'[^a-z0-9]+', '-', cleaned).strip('-')
    return cleaned

